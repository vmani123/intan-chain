#!/usr/bin/env python3
"""Generate the C header and Python module that encode CONTRACTS.md.

The frame layout, datagram size and register map live in exactly one place --
CONTRACTS.md, mirrored by the table below -- and two of the three consumers are
generated from it. The third (the FPGA RTL) cannot be generated, so it carries
the same numbers as localparams and `make check-contract` is what tells you when
they have drifted.

Usage:
    python3 tools/gen_contract.py            # write the generated files
    python3 tools/gen_contract.py --check    # exit 1 if they are stale
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

# ---------------------------------------------------------------------------
# The single source of truth. Keep in step with CONTRACTS.md.
# ---------------------------------------------------------------------------
CONSTANTS = [
    ("MAGIC",            0xA55A, "frame magic number"),
    ("TYPE_RAW16",       0,      "payload is n_ch x int16"),
    ("TYPE_COMPRESSED",  2,      "payload is a codec blob"),
    ("FLAG_REALISTIC",   1 << 0, "pattern mode: smooth rather than LFSR"),
    ("FLAG_CODEC",       1 << 1, "codec enabled"),
    ("HDR_BYTES",        20,     "frame header size"),
    ("TRAILER_BYTES",    12,     "ESP trailer size, appended once per datagram"),
    ("N_CH",             128,    "channels (2 x RHD2164)"),
    ("FRAMES_PER_DGRAM", 5,      "frames per UDP datagram"),
    ("SYS_CLK_HZ",       96_000_000, "FPGA fast clock"),
    ("OVERSAMPLE",       4,      "fast-clock ticks per SCLK bit"),
    ("CMDS_PER_SAMPLE",  35,     "32 CONVERT + 3 AUX"),
    ("CMD_TICKS",        84,     "SPI ticks per CS cycle"),
    ("CAP_TAPS",         78,     "MISO taps recorded per CS cycle"),
    ("PHASE_MAX",        15,     "largest PHASE_SELECT"),
    ("SPI_DIV_MAX",      15,     "largest SPI_DIV"),
    ("DIAG_DEPTH",       64,     "diagnostic list entries"),
    ("UART_BAUD",        115200, "control interface"),
    ("UDP_PORT",         5001,   "data"),
    ("ECHO_PORT",        5002,   "clock-offset probe"),
    ("ID_EXPECTED",      0x1C100002, "value of register 0x1F"),
]

# name, struct format, byte offset
HDR_FIELDS = [
    ("magic",       "H", 0),
    ("type",        "B", 2),
    ("flags",       "B", 3),
    ("seq",         "I", 4),
    ("t_cap",       "I", 8),
    ("t_tx",        "I", 12),
    ("n_ch",        "H", 16),
    ("payload_len", "H", 18),
]

TRAILER_FIELDS = [
    ("esp_rx_us",  "I", 0),
    ("esp_tx_us",  "I", 4),
    ("pipe_depth", "I", 8),
]

REGISTERS = [
    ("CTRL",          0x00, "bit0 run, bit1 clear_counters"),
    ("SAMPLE_PERIOD", 0x01, "fast-clock ticks between sample starts"),
    ("PHASE_SELECT",  0x02, "0..15, MISO sampling phase in SPI ticks"),
    ("MODE",          0x03, "bit0 realistic, bit1 codec, bit2 internal pattern, bit3 loopback"),
    ("SPI_DIV",       0x04, "0..15, SCLK = 24 MHz / (SPI_DIV + 1)"),
    ("FRAMES",        0x10, "frames built"),
    ("DGRAMS",        0x11, "datagrams sent to QSPI"),
    ("FIFO_HIGH",     0x12, "FIFO high-water, in slots"),
    ("OVERRUNS",      0x13, "datagrams dropped, FIFO full"),
    ("STALLS",        0x14, "cycles waiting on the ESP ready line"),
    ("SPI_CYCLES",    0x15, "CS cycles issued"),
    ("LINK_CHECKS",   0x16, "sweeps whose READ(59) result was checked"),
    ("LINK_ERR0",     0x17, "chip 0 check failures, [15:0] A, [31:16] B"),
    ("LINK_ERR1",     0x18, "chip 1 check failures, [15:0] A, [31:16] B"),
    ("LINK_LAST0",    0x19, "chip 0 last READ(59), [15:0] A, [31:16] B"),
    ("LINK_LAST1",    0x1A, "chip 1 last READ(59), [15:0] A, [31:16] B"),
    ("MISO_STAT",     0x1B, "seen-low/high flags, live levels, loopback"),
    ("MISO_EDGES0",   0x1C, "miso0 transitions while CS low"),
    ("MISO_EDGES1",   0x1D, "miso1 transitions while CS low"),
    ("CAPS",          0x1E, "[7:0] QSPI_DIV, bit8 emulator, [23:16] taps"),
    ("ID",            0x1F, "magic + version"),
    ("DIAG_PTR",      0x20, "diagnostic list index"),
    ("DIAG_CMD",      0x21, "list entry at DIAG_PTR; write increments"),
    ("DIAG_LEN",      0x22, "commands in the list, 1..64"),
    ("DIAG_CTRL",     0x23, "W bit0 go; R bit0 busy, bit1 done, bit2 rejected"),
    ("DIAG_RES0",     0x24, "chip 0 decoded, [15:0] A, [31:16] B"),
    ("DIAG_RES1",     0x25, "chip 1 decoded, [15:0] A, [31:16] B"),
    ("DIAG_RAW0_0",   0x26, "miso0 taps 0..31"),
    ("DIAG_RAW0_1",   0x27, "miso0 taps 32..63"),
    ("DIAG_RAW0_2",   0x28, "miso0 taps 64..77"),
    ("DIAG_RAW1_0",   0x29, "miso1 taps 0..31"),
    ("DIAG_RAW1_1",   0x2A, "miso1 taps 32..63"),
    ("DIAG_RAW1_2",   0x2B, "miso1 taps 64..77"),
]

CTYPE = {"B": "uint8_t", "H": "uint16_t", "I": "uint32_t"}
BANNER = "/* GENERATED by tools/gen_contract.py from CONTRACTS.md. DO NOT EDIT. */"
PY_BANNER = '"""GENERATED by tools/gen_contract.py from CONTRACTS.md. DO NOT EDIT."""'


def gen_header() -> str:
    L = [BANNER, "#pragma once", "#include <stdint.h>", ""]
    for name, val, why in CONSTANTS:
        L.append(f"#define CHAIN_{name:<18} {val:#x}   /* {why} */")
    L += ["",
          "/* Frame payload and total sizes for RAW16 at CHAIN_N_CH channels. */",
          "#define CHAIN_RAW16_PAYLOAD  (CHAIN_N_CH * 2)",
          "#define CHAIN_RAW16_FRAME    (CHAIN_HDR_BYTES + CHAIN_RAW16_PAYLOAD)",
          "#define CHAIN_DGRAM_PAYLOAD  (CHAIN_FRAMES_PER_DGRAM * CHAIN_RAW16_FRAME)",
          "#define CHAIN_DGRAM_BYTES    (CHAIN_DGRAM_PAYLOAD + CHAIN_TRAILER_BYTES)",
          "",
          "typedef struct __attribute__((packed)) {"]
    for name, fmt, _off in HDR_FIELDS:
        L.append(f"    {CTYPE[fmt]:<9} {name};")
    L += ["} chain_hdr_t;",
          "",
          '_Static_assert(sizeof(chain_hdr_t) == CHAIN_HDR_BYTES, "header must be 20 bytes packed LE");',
          "",
          "typedef struct __attribute__((packed)) {"]
    for name, fmt, _off in TRAILER_FIELDS:
        L.append(f"    {CTYPE[fmt]:<9} {name};")
    L += ["} chain_trailer_t;",
          "",
          '_Static_assert(sizeof(chain_trailer_t) == CHAIN_TRAILER_BYTES, "trailer must be 12 bytes packed LE");',
          "",
          "/* UART control registers. */"]
    for name, addr, why in REGISTERS:
        L.append(f"#define CHAIN_REG_{name:<14} {addr:#04x}   /* {why} */")
    L.append("")
    return "\n".join(L)


def gen_python() -> str:
    L = [PY_BANNER, "import struct", ""]
    for name, val, why in CONSTANTS:
        L.append(f"{name} = {val}  # {why}")
    L += ["",
          "RAW16_PAYLOAD = N_CH * 2",
          "RAW16_FRAME = HDR_BYTES + RAW16_PAYLOAD",
          "DGRAM_PAYLOAD = FRAMES_PER_DGRAM * RAW16_FRAME",
          "DGRAM_BYTES = DGRAM_PAYLOAD + TRAILER_BYTES",
          "",
          "HDR_FMT = " + repr("<" + "".join(f for _n, f, _o in HDR_FIELDS)),
          "HDR_FIELDS = " + repr([n for n, _f, _o in HDR_FIELDS]),
          "TRAILER_FMT = " + repr("<" + "".join(f for _n, f, _o in TRAILER_FIELDS)),
          "TRAILER_FIELDS = " + repr([n for n, _f, _o in TRAILER_FIELDS]),
          "",
          "assert struct.calcsize(HDR_FMT) == HDR_BYTES",
          "assert struct.calcsize(TRAILER_FMT) == TRAILER_BYTES",
          "",
          "REG = {"]
    for name, addr, why in REGISTERS:
        L.append(f"    {name!r}: {addr:#04x},  # {why}")
    L += ["}", ""]
    return "\n".join(L)


TARGETS = [
    ("esp/main/chain_contract.h", gen_header),
    ("host/chain/contract.py", gen_python),
]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if a generated file is missing or stale")
    args = ap.parse_args()

    stale = []
    for rel, fn in TARGETS:
        path = ROOT / rel
        want = fn()
        if args.check:
            if not path.exists() or path.read_text() != want:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(want)
            print(f"wrote {rel}")

    if stale:
        print("STALE (run `make contract`): " + ", ".join(stale), file=sys.stderr)
        return 1
    if args.check:
        print("contract files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
